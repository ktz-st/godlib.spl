# DCK emits MOVE.W d16(a0),d16(a1) per selected plane. Keep that for partial
# masks; adjacent selected planes use MOVE.L. Full-plane copies use MOVEM.
lines=['; Generated by tools/assets.py. Entire rectangle loops; one call per block.', 'Db_RowTable:']
for groups in (2,8,20):
 lines.append('        dc.l '+','.join('Db_Row%d_%d'%(groups,m)for m in range(16)))
lines.append('Db_RowsStart:')
for groups in (2,8,20):
 for mask in range(16):
  lines.append('Db_Row%d_%d:'%(groups,mask))
  if mask==15:
   pos=0;remaining=groups*8
   while remaining:
    count=min(13,remaining//4);regs='d0'if count==1 else ('d0-d%d'%(count-1)if count<=8 else'd0-d7/a2'+(''if count==9 else'-a%d'%(count-7)))
    if count==1:lines.append('        move.l %d(a0),%d(a1)'%(pos,pos))
    else:lines.extend(['        movem.l %d(a0),%s'%(pos,regs),'        movem.l %s,%d(a1)'%(regs,pos)])
    pos+=count*4;remaining-=count*4
  else:
   for g in range(groups):
    p=0
    while p<4:
     if mask&(1<<p):
      paired=p<3 and mask&(1<<(p+1));off=g*8+p*2
      lines.append('        move.%s %d(a0),%d(a1)'%('l'if paired else'w',off,off));p+=2 if paired else 1
     else:p+=1
  if mask==15 and groups!=2:
   lines.extend(['        adda.w 4(sp),a0','        adda.w 6(sp),a1','        subq.w #1,8(sp)','        bpl.w Db_Row%d_%d'%(groups,mask)])
  else:
   lines.extend(['        adda.w d4,a0','        adda.w d5,a1','        dbf d6,Db_Row%d_%d'%(groups,mask)])
  lines.append('        rts')
lines.append('Db_RowsEnd:')
(r/'assets/rows.inc').write_text('\n'.join(lines)+'\n')
