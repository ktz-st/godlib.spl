"""ABC2 castle and offline-generated 68000 lens sampler (8 horizontal phases)."""
from pathlib import Path
from PIL import Image
import math,struct,hashlib,json,sys
root=Path(__file__).resolve().parent
sys.path.insert(0,str(root.parent/'tools'))
from abc2_assets import convert,pack
src=root.parent/'water/assets/castle-source.png'
im=Image.open(src).convert('RGB').resize((320,200),Image.Resampling.LANCZOS)
words,indices,preview,meta=convert(im,planes=4,locks={15:0xfff})
(root/'assets/IMAGE.BIN').write_bytes(pack(indices,320,200,4))
(root/'assets/PALETTE.BIN').write_bytes(struct.pack('>16H',*words))
preview.save(root/'assets/castle-ste.png')
(root/'assets/SINE.BIN').write_bytes(struct.pack('>256h',*[round(127*math.sin(i*2*math.pi/256))for i in range(256)]))
for group,positions in enumerate([(0,1,2),(3,4,5),(6,7)]):
 data=bytearray()
 for index in range(16**len(positions)):
  value=0
  for n,pos in enumerate(positions):
   colour=(index>>(4*n))&15
   for plane in range(4):value|=((colour>>plane)&1)<<(31-8*plane-pos)
  data.extend(struct.pack('>I',value))
 (root/f'assets/LUT{group}.BIN').write_bytes(data)

def sample(dx,dy):
 r2=dx*dx+dy*dy
 if r2>=1024:return dx,dy,None
 # A fine white rim makes the footprint clear; no palette/bitplane trick.
 if r2>=31.3**2:return 0,0,15
 factor=1/(1+1.0*(1-r2/1024)**1.25)
 return round(dx*factor),round(dy*factor),None

code=['; Generated by prepare.py; do not edit.','; EOR-free gather: source words contain c*4, c*64 and c*1024.']
counts=[]
for phase in range(8):
 groups=[]
 for dy in range(-32,32):
  for q in range(-4,5):
   dx0=q*8-phase
   if not any((dx0+j)**2+dy*dy<1024 for j in range(8)):continue
   groups.append((dy,q,dx0))
 code.append(f'Lens_K{phase}:')
 for parity in [0,1]:
  if parity:
   code += ['        tst.w d7',f'        beq.w Lens_Odd{phase}','        addq.l #6,a0',f'Lens_Odd{phase}:']
  for dy,q,dx0 in groups:
   if (q&1)!=parity:continue
   def operand(j,shift):
    sx,sy,fixed=sample(dx0+j,dy)
    if fixed is not None:return '#'+str(fixed<<shift)
    return f'{sy*640+sx*2}(a{2+(shift-2)//4})'
   code += [f'        move.w {operand(0,2)},d0',f'        add.w {operand(1,6)},d0',f'        add.w {operand(2,10)},d0','        move.l (a5,d0.w),d1',
            f'        move.w {operand(3,2)},d0',f'        add.w {operand(4,6)},d0',f'        add.w {operand(5,10)},d0','        or.l (a6,d0.w),d1',
            f'        move.w {operand(6,2)},d0',f'        add.w {operand(7,6)},d0','        or.l (a1,d0.w),d1',f'        movep.l d1,{dy*160+(q//2)*8+(q&1)}(a0)']
 code.append('        rts');counts.append(len(groups))
(root/'assets/kernel.inc').write_text('\n'.join(code)+'\n')
meta.update(source='../water/assets/castle-source.png',source_sha256=hashlib.sha256(src.read_bytes()).hexdigest(),radius=32,zoom=2,phase_groups=counts,algorithm='inverse radial magnification; factor=1/(1+(1-r2/1024)^1.25); white rim at r>=31.3')
(root/'assets/provenance.json').write_text(json.dumps(meta,indent=2)+'\n')
print('Lens: ABC2 16 colours, phase groups',counts)
