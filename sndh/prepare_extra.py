#!/usr/bin/env python3
"""Offline keyboard/masks, PSG phase steps and compiled expanding-circle deltas."""
from pathlib import Path
import struct
p=Path(__file__).resolve().parent/'assets'
# 80 semitones C1..G7, 47 white keys of width 6; center the 282px keyboard.
white={0,2,4,5,7,9,11};pixels=[0]*(320*64);owner=[-1]*len(pixels);column=0;starts={}
for note in range(80):
 if note%12 not in white:continue
 x=19+column*6;starts[note]=x;column+=1
 for y in range(64):
  for xx in range(x,x+6):
   i=y*320+xx;pixels[i]=3
   if 1<=y<63 and x<xx<x+5:pixels[i]=1;owner[i]=note
for note in range(80):
 if note%12 in white:continue
 x=starts[note-1]+4
 for y in range(39):
  for xx in range(x,x+4):i=y*320+xx;pixels[i]=2;owner[i]=note
image=bytearray()
for y in range(64):
 for x in range(0,320,16):
  vals=pixels[y*320+x:y*320+x+16]
  image+=struct.pack('>4H',*[sum(((v>>plane)&1)<<(15-j)for j,v in enumerate(vals))for plane in range(4)])
(p/'PIANO.BIN').write_bytes(image)
records=bytearray();offsets=[]
for note in range(80):
 words={}
 for i,key in enumerate(owner):
  if key==note:
   y,x=divmod(i,320);off=y*160+(x//16)*8;words[off]=words.get(off,0)|(0x8000>>(x&15))
 offsets.append(len(records));records+=struct.pack('>H',len(words))
 for off,mask in sorted(words.items()):records+=struct.pack('>HH',off,mask)
(p/'KEYS.BIN').write_bytes(records);(p/'KEYOFF.BIN').write_bytes(struct.pack('>80I',*offsets))
(p/'SCOPESTEP.BIN').write_bytes(struct.pack('>4096H',*[min(65535,327680//max(1,n))for n in range(4096)]))
# Midpoint circle, grouped into planar words. Ages 1..24 -> radii 2..48.
frames=[{}]
for age in range(1,25):
 radius=age*2;x=radius;y=0;err=1-radius;points=set()
 while x>=y:
  points.update([(x,y),(y,x),(-y,x),(-x,y),(-x,-y),(-y,-x),(y,-x),(x,-y)])
  y+=1
  if err<0:err+=2*y+1
  else:x-=1;err+=2*(y-x)+1
 words={}
 for x,y in points:
  off=y*160+(x//16)*8;words[off]=words.get(off,0)|(0x8000>>(x&15))
 frames.append(words)


# Native 68000 immediate-XOR kernels. A two-frame delta is the usual transition
# because each logical display page is revisited every other rendered frame.
# Arbitrary retriggers/mode changes use standalone frame erase/draw kernels.
lines=['; Generated by prepare_extra.py. a3 = circle origin/plane.', '; Dispatcher supplies d3=$8000, d4=8, d5=1, d6=2.', 'Rings_Kernels:']
common={0x8000:'d3',0x0008:'d4',0x0001:'d5',0x0002:'d6'}
for kind in ['Single','Delta2']:
 lines.append('Rings_'+kind+'Offsets:')
 lines.extend('        dc.l Rings_%s%d-Rings_Kernels'%(kind,age)for age in range(25))
for kind in ['Single','Delta2']:
 for age in range(25):
  words=dict(frames[age])
  if kind=='Delta2' and age>2:
   for off,mask in frames[age-2].items():words[off]=words.get(off,0)^mask
  lines.append('Rings_%s%d:'%(kind,age))
  for off,mask in sorted(words.items()):
   if mask in common:lines.append('        eor.w %s,%d(a3)'%(common[mask],off))
   elif mask==65535:lines.append('        not.w %d(a3)'%off)
   elif mask:lines.append('        eori.w #$%04x,%d(a3)'%(mask,off))
  lines.append('        rts')
(p/'RINGS.S').write_text('\n'.join(lines)+'\n')
print('Keyboard, 80 key masks, PSG phase steps and compiled ring kernels generated.')

# Fixed 57px-diameter discs, radius 28; a 64px mono stamp, center at x=32.
mask=bytearray()
for y in range(57):
 for x in range(0,64,16):
  bits=sum((1<<(15-j))for j in range(16)if (x+j-32)**2+(y-28)**2<=28**2)
  mask+=struct.pack('>H',bits)
(p/'ORGAN.BIN').write_bytes(mask)
# STE intensity n: bits 3..1 occupy hardware bits 2..0; bit 0 occupies bit 3.
# Existing VU state v+1 represents fixed PSG volume v; state 16 is max/ENV.
intensities=[0,0]+list(range(1,16))
pal=[(((n>>1)|((n&1)<<3))<<shift)for shift in [8,4,0]for n in intensities]
(p/'ORGANPAL.BIN').write_bytes(struct.pack('>51H',*pal))
