"""ABC2 eight-colour STE winter art; plane 3 stays available to the snow."""
from pathlib import Path
from PIL import Image
import json,struct,sys
root=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(root.parent/'tools'))
from abc2_assets import convert,pack,rgb
img=Image.open(root/'assets/winter-source.png').convert('RGB').resize((320,200),Image.Resampling.NEAREST)
words,indices,_,meta=convert(img,planes=3,locks={4:0x9bc,7:0xfff})
palette=[rgb(w) for w in words]
# Preserve the original collision silhouette: zero is air; all other colours
# are solid. RGB palette fitting must not change where flakes settle.
solid=[]
for i,(r,g,b) in enumerate(img.getdata()):
 air=r<18 and g<38 and b<70
 if air:indices[i]=0
 elif indices[i]==0:indices[i]=min(range(1,8),key=lambda j:sum((v-w)**2 for v,w in zip((r,g,b),palette[j])))
 solid.append(not air)
for y in range(200):
 for x in range(320):
  if y<24:indices[y*320+x]=0;solid[y*320+x]=False
  elif x in (0,319) or y==199:indices[y*320+x]=1;solid[y*320+x]=True
assert all(bool(i)==s for i,s in zip(indices,solid)) and max(indices)<8
raw=pack(indices,320,200,4)
assert all(raw[i:i+2]==b'\0\0' for i in range(6,len(raw),8))
(root/'assets/WINTER.BIN').write_bytes(raw)
colours=words+[0xfff]*8
(root/'assets/palette.h').write_text('/* Generated by tools/prepare.py: ABC2 STE, no dithering. */\nstatic U16 gSnowPalette[16]={'+','.join(hex(c) for c in colours)+'};\n')
preview=Image.new('RGB',(320,200));preview.putdata([palette[i] for i in indices]);preview.save(root/'assets/winter-st.png')
meta.update({'collision_silhouette_preserved':True,'snow_plane_3_clear':True,'postprocess':'Preserve original air/solid mask, clear header, close screen edges; no dithering'})
(root/'assets/winter-st.png.json').write_text(json.dumps(meta,indent=2)+'\n')
print('WINTER.BIN: ABC2 eight-colour STE, no dithering; collision silhouette preserved')
