"""Convert the generated castle with ABC2 for STE (no dithering) and bake Ugh intro row-remapping states."""
from pathlib import Path
from PIL import Image
import json,struct,sys
r=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(r.parent/'tools'))
TOP=112;HEIGHT=200-TOP;SURFACE=TOP-1
length=[6,1,4,1,6,1,4,1,7,1,5,1,7,1,5,1,8,1,6,1,8,1,6,1]
advance=[1,0,1,0,1,2,1,2]*3
im=Image.open(r/'assets/castle-source.png').convert('RGB').resize((320,200),Image.Resampling.LANCZOS)
from abc2_assets import save
_,pixels=save(im,r/'assets/CASTLE.PI1',r/'assets/castle-st.png')
def packrow(row):
 out=bytearray()
 for x in range(0,320,16):
  for p in range(4):out+=struct.pack('>H',sum(((row[x+i]>>p)&1)<<(15-i) for i in range(16)))
 return out
# The flat waterline is row 111 in the resized generated scene; water fills
# every pixel below it. Surface glints use three small horizontal phases.
surface=pixels[SURFACE*320:(SURFACE+1)*320]
(r/'assets/SURFACE.BIN').write_bytes(b''.join(packrow(surface[dx:]+surface[:dx]) for dx in (0,4,8)))
rows=[];states=[];phase=0;remaining=1
for tick in range(84):
 states.append({'phase':phase,'remaining':remaining})
 entry=phase;event=TOP+remaining;step=1;source=TOP;maprows=[]
 for y in range(TOP,200):
  if y==event:
   step=advance[entry];event+=length[entry];entry=(entry+1)%24
  if y>=197:step=0
  maprows.append(min(source,199));source+=step
 assert all(TOP<=y<200 for y in maprows)
 rows.extend(y*160 for y in maprows)
 remaining-=1
 if remaining==0:
  phase=(phase+1)%24;remaining=length[phase]
assert (phase,remaining)==(0,1)
rows.extend(y*160 for y in range(TOP,200));rows.extend([0xffff]*HEIGHT)
(r/'assets/ROWS.BIN').write_bytes(struct.pack('>'+str(len(rows))+'H',*rows))
(r/'assets/config.h').write_text('/* Generated by tools/prepare.py. */\n#define WATER_TOP 112\n#define WATER_HEIGHT 88\n#define WATER_STATES 84\n')
(r/'assets/wave.json').write_text(json.dumps({'source':'ugh.agt/src/openugh/intro_water_wave.h','water_top':TOP,'height':HEIGHT,'surface_y':SURFACE,'hold_y':197,'lengths':length,'advance':advance,'states':states},indent=2)+'\n')
print('CASTLE.PI1: 320x200, 16 STE colours, ABC2 without dithering; horizontal surface y=111; animated water y=112..199')
